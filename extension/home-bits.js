/* Home's small bits in the house look (4.2, roadmap item 6, owner: "Bring the plain bits into the art"): the greeting
   on All courses, the chips New / Overdue / Due today / Tomorrow, and the drawn controls Edit Home and Undo move.
   Nothing here draws. Every bit names an ART SLOT: a drawing the artist may add later as art/bits/<slot>.svg, which
   `npm run bits-art` (scripts/bits-art.cjs) checks and writes into the generated block below. Until a slot holds a
   drawing, the bit uses an existing drawn piece (the fallback named in SLOTS), so a drawing drops in without a code change.
   Pure functions, no DOM: dashboard-view.js and hand-in.js call them; tests run them under a fixed clock. */
(function(root){
 'use strict';
 // ---- the art slots: what each holds, at what size, where it shows, and what stands in for it today ----
 // use 'scene': a whole heading drawing, root viewBox "0 0 W 240" (480 <= W <= 1680), drawn like art/home.svg (art/README.md,
 //   "All courses is a panorama"): the rightmost 480 units always show, the rest is cut from the left in narrow windows.
 // use 'icon':  a drawing beside a word, root viewBox "0 0 40 40", shown at 20 x 20 px; ink may use currentColor.
 // use 'frame': a stretchable label, root viewBox "0 0 <w> <h>"; the edges in `slice` (top right bottom left, in units) keep
 //   their size and the middle stretches with the words (CSS border-image). fill: true, the drawing is the whole label;
//   false, only its edges are drawn and the middle stays the page's paper (a bookmark keeps its course's wash).
 const GREET_WHERE='the All courses heading (the drawing beside the greeting, 200-240 px tall, right-anchored)';
 const greetSlot=(name,when)=>[name,{use:'scene',minW:480,maxW:1680,h:240,max:65536,where:GREET_WHERE+', '+when,fallback:'art/home.svg (the All courses scene, the greeting’s drawing today)'}];
 const SLOTS=Object.freeze(Object.fromEntries([
  greetSlot('greet-early','early morning, 5:00-7:59'),
  greetSlot('greet-morning','morning, 8:00-11:59'),
  greetSlot('greet-midday','midday, 12:00-13:59'),
  greetSlot('greet-afternoon','afternoon, 14:00-16:59'),
  greetSlot('greet-evening','evening, 17:00-21:59'),
  greetSlot('greet-late','late night, 22:00-4:59'),
  greetSlot('greet-weekend','Saturday and Sunday'),
  greetSlot('greet-clear','a day with nothing open due today and nothing overdue'),
  greetSlot('greet-overdue','a day when something went overdue (today or yesterday)'),
  greetSlot('greet-test','the day before a test, quiz or exam'),
  ['ctl-edit-home',{use:'icon',w:40,h:40,max:6144,where:'Edit Home / Done editing, at the end of Home’s filter row',fallback:'the Move things around feature drawing (addons-art.js icons.arrange)'}],
  ['ctl-undo-move',{use:'icon',w:40,h:40,max:6144,where:'Undo move, beside Edit Home, only while a move can be undone',fallback:'the top bar’s refresh drawing, its upper arrow turned back (dashboard-view.js TB.refresh)'}],
  ['ctl-show-info',{use:'icon',w:40,h:40,max:6144,where:'Show course information, beside Edit Home, only while it is hidden',fallback:'the Course information module glyph (widgets.js glyph(‘context’))'}],
  ['chip-new',{use:'frame',w:60,h:22,slice:[11,8,11,12],fill:true,max:4096,where:'the New chip under the Home heading',fallback:'the punched paper tag (refresh.css .rd-study-tag), kraft with a sage tint'}],
  ['chip-overdue',{use:'frame',w:60,h:22,slice:[11,8,11,12],fill:true,max:4096,where:'the Overdue chip under the Home heading; the late and missing chips of To hand in',fallback:'the punched paper tag, kraft with a red tint'}],
  ['chip-today',{use:'frame',w:60,h:22,slice:[11,8,11,12],fill:true,max:4096,where:'the Due today chip under the Home heading; the Today chip of To hand in',fallback:'the punched paper tag, kraft with an amber tint'}],
  ['chip-tomorrow',{use:'frame',w:60,h:22,slice:[11,8,11,12],fill:true,max:4096,where:'the Tomorrow chip under the Home heading; the Tomorrow chip of To hand in',fallback:'the punched paper tag, kraft with a blue tint'}],
  ['bookmark-slip',{use:'frame',w:90,h:40,slice:[12,12,12,12],fill:false,max:6144,where:'each bookmark in the Bookmarks bar (about 170-270 x 34-44 px)',fallback:'the planner card’s soft pen edge (refresh.css --rd-pen-soft) with the course’s wash at the left'}]
 ]));
 // <bits:generated>
// Generated by scripts/bits-art.cjs from art/bits/*.svg. Do not edit by hand: run npm run bits-art.
const ART={};
// </bits:generated>
 const has=slot=>Object.hasOwn(ART,slot)&&Object.hasOwn(SLOTS,slot);
 const HIDDEN=' aria-hidden="true" focusable="false"';
 // An icon slot's drawing (or '' when the slot is empty: the caller keeps its fallback).
 function icon(slot,cls='rd-bit-art'){if(!has(slot)||SLOTS[slot].use!=='icon')return '';return `<svg class="${cls}" data-slot="${slot}" viewBox="0 0 ${SLOTS[slot].w} ${SLOTS[slot].h}"${HIDDEN}>${ART[slot].inner}</svg>`;}
 // A scene slot's drawing, with the root course-art.js gives a scene (refresh.css lays it out the same way), or ''.
 function scene(slot,{place='heading'}={}){
  if(!has(slot)||SLOTS[slot].use!=='scene')return '';const a=ART[slot],w=a.w,wide=w>480,place_=String(place).replace(/[^\w-]/g,'');
  return `<svg class="rd-art" data-art="${slot}" data-crop="wide" data-place="${place_}" data-rd-key="art-${slot}-wide"${a.cycle?` data-cycle="${a.cycle}"`:''} viewBox="0 0 ${w} 240"${wide?` preserveAspectRatio="xMaxYMid slice"${HIDDEN} data-wide="true" style="--rd-art-w:${w}"`:` preserveAspectRatio="xMidYMid meet"${HIDDEN}`}>${a.inner}</svg>`;
 }
 // A frame slot as a CSS url() (single quotes, nothing that ends an HTML attribute), or ''.
 function frame(slot){if(!has(slot)||SLOTS[slot].use!=='frame')return '';return `url('data:image/svg+xml,${encodeURIComponent(ART[slot].svg).replace(/'/g,'%27').replace(/\(/g,'%28').replace(/\)/g,'%29')}')`;}

 // ---- the chip: ONE component for New, Overdue, Due today and Tomorrow, wherever they show ----
 // The chip keeps its element and its words (the words, never the colour alone, say what it is); chipAttrs gives the
 // kind and, once the kind's slot holds a drawing, that drawing as the label (refresh.css "Home bits": .rd-bit-chip).
 const CHIP_KINDS=Object.freeze(['new','overdue','today','tomorrow']);
 const chipKind=value=>CHIP_KINDS.includes(value)?value:({danger:'overdue',late:'overdue',missing:'overdue',warn:'today',info:'tomorrow',success:'new'})[value]||'';
 function chipAttrs(kind){const k=chipKind(kind);if(!k)return '';const art=frame('chip-'+k);return ` data-chip="${k}"${art?` data-chip-art="true" style="--chip-art:${art}"`:''}`;}
 // A chip that is not a control (a status beside a row): a span with the chip's class, kind and words.
 function chip(kind,text,{cls='',tone=''}={}){
  const E=root.ReserveUI?.escapeHTML||(v=>String(v??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c])));
  return `<span class="${cls?cls+' ':''}rd-bit-chip"${tone?` data-tone="${E(tone)}"`:''}${chipAttrs(kind)}>${E(text)}</span>`;
 }

 // ---- the greeting: a table of variants by the time of day and the day's situation ----
 // Short and warm, never nagging, nothing a teacher would not say. The student's first name (from Canvas, as before)
 // follows the line after a comma. {day} is the weekday's name. Lines stay within 22 characters (tests/home-bits).
 const GREETINGS=Object.freeze([
  {id:'late',slot:'greet-late',when:'22:00-4:59, every day',lines:['Working late','Late-night study','Quiet hours']},
  {id:'test',slot:'greet-test',when:'5:00-21:59, the day before an open test, quiz or exam',lines:['Good luck tomorrow','Big day tomorrow','You’ve got this']},
  {id:'overdue',slot:'greet-overdue',when:'5:00-21:59, something open went overdue today or yesterday',lines:['One step at a time','Glad you’re here','Good to see you']},
  {id:'weekend',slot:'greet-weekend',when:'5:00-21:59, Saturday or Sunday',lines:['Happy {day}','Enjoy your weekend','A slower day']},
  {id:'clear',slot:'greet-clear',when:'5:00-21:59 on a weekday with nothing open due today and nothing overdue',lines:['A clear day','All clear today','Room to breathe']},
  {id:'early',slot:'greet-early',when:'5:00-7:59',lines:['Good morning','Early start','Bright and early']},
  {id:'morning',slot:'greet-morning',when:'8:00-11:59',lines:['Good morning','Morning','Have a good morning']},
  {id:'midday',slot:'greet-midday',when:'12:00-13:59',lines:['Good afternoon','Midday already','Hope lunch was good']},
  {id:'afternoon',slot:'greet-afternoon',when:'14:00-16:59',lines:['Good afternoon','Afternoon','Hello this afternoon']},
  {id:'evening',slot:'greet-evening',when:'17:00-21:59',lines:['Good evening','Evening','Hope today went well']}
 ].map(Object.freeze));
 const BY_ID=new Map(GREETINGS.map(g=>[g.id,g]));
 // The clock in the student's time zone: the hour (0-23), the weekday (0 = Sunday) and its name, and the day's key.
 const clocks=new Map();
 function clock(now,timeZone){
  const zone=timeZone||'America/New_York';let f=clocks.get(zone);
  if(!f){
   try{
    f=new Intl.DateTimeFormat('en-US',{timeZone:zone,hourCycle:'h23',hour:'numeric',weekday:'long',year:'numeric',month:'2-digit',day:'2-digit'});
   }catch{f=new Intl.DateTimeFormat('en-US',{hourCycle:'h23',hour:'numeric',weekday:'long',year:'numeric',month:'2-digit',day:'2-digit'});}
   if(clocks.size>=16)clocks.clear();
   clocks.set(zone,f);
  }
  const p=Object.fromEntries(f.formatToParts(new Date(now)).map(x=>[x.type,x.value]));
  return {hour:Number(p.hour)%24,day:p.weekday,weekday:['Sunday','Monday','Tuesday','Wednesday','Thursday','Friday','Saturday'].indexOf(p.weekday),key:`${p.year}-${p.month}-${p.day}`};
 }
 // Which variant, by precedence: late night; the day before a test; something gone overdue today or yesterday; the
 // weekend; a clear weekday; else the time of day. `situation` comes from the same counts as the chips (dashboard.js
 // glance): {overdue, today, slipped, testTomorrow}.
 function variant(t,situation={}){
  const s=situation||{},h=t.hour;
  if(h>=22||h<5)return 'late';
  if(s.testTomorrow>0)return 'test';
  if(s.slipped>0)return 'overdue';
  if(t.weekday===0||t.weekday===6)return 'weekend';
  if(!(s.today>0)&&!(s.overdue>0))return 'clear';
  return h<8?'early':h<12?'morning':h<14?'midday':h<17?'afternoon':'evening';
 }
 const hash=value=>{let h=2166136261;for(const c of String(value))h=Math.imul(h^c.charCodeAt(0),16777619);return h>>>0;};
 // The line, chosen steadily: once per visit (memo: an object that lives as long as the page's Home, dashboard-view's
 // heading cache), by the day, the variant and the hour it was first shown; a new line only on another day or variant.
 // Without a memo it is the same line all hour.
 function greeting({now=Date.now(),timeZone,name='',situation={},memo=null}={}){
  const t=clock(now,timeZone),id=variant(t,situation),g=BY_ID.get(id);
  let index;const kept=memo&&memo.greet;
  if(kept&&kept.id===id&&kept.key===t.key&&kept.index<g.lines.length)index=kept.index;
  else{index=hash(`${id}|${t.key}|${t.hour}`)%g.lines.length;if(memo)memo.greet={id,key:t.key,index};}
  const line=g.lines[index].replace('{day}',t.day),first=String(name||'').trim().split(/\s+/)[0]||'';
  return {id,slot:g.slot,line,text:first?`${line}, ${first}`:line,index};
 }
 // Is this open work a test? (a quiz, test or exam by its name or its Canvas type; a review, corrections or practice is not)
 const TEST=/\b(?:tests?|exams?|quiz(?:zes)?|midterms?|final exams?)\b/i,NOT_TEST=/\b(?:review|corrections?|practice|prep|study guide|retake form)\b/i;
 function isTest(item){const name=String(item?.name||'');return !NOT_TEST.test(name)&&(TEST.test(name)||(item?.submissionTypes||[]).includes('online_quiz'));}

 const api={SLOTS,ART,has,icon,scene,frame,CHIP_KINDS,chipKind,chipAttrs,chip,GREETINGS,clock,variant,greeting,isTest};
 root.ReserveHomeBits=api;if(typeof module==='object'&&module.exports)module.exports=api;
})(globalThis);
